#pragma once

/**
 * @file modelKeys.h
 * @brief Клавиши модели без профиля: чем отвечает программа на вопрос «какие клавиши у модели».
 *
 * Два вопроса держатся раздельно (шаг K4), иначе ответ противоречит себе:
 *
 * 1. «Есть ли у модели такая клавиша» — только подтверждённые источники: зоны вида `Key`
 *    профиля, скан-таблица семейства или модели (K2), таблица надписей по модели. Для
 *    архитектур 11 и 15 этого источника без профиля нет.
 * 2. «Можно ли на это назначить» — физические клавиши плюс имена ячеек экрана профиля:
 *    в конфигурации 1000/1100 они обращают с собой как с именованными кнопками.
 *
 * `modelKeys()` отвечает на второй вопрос, `complete` — на первый. Проверка (C1) предупреждает
 * только когда список исчерпывающий и имени в нём нет; UI-списки (`modelKeyIds`) отвечают на
 * второй вопрос.
 *
 * Ядро видит реестр оформлений, но не их содержимое: имена зон и ключи экранов передаёт
 * приложение (`modelKeysQt`, шаг A1). Здесь нет кеша — функция чистая; вызывать её нужно из
 * обновления таблиц, гейтов и диалогов, а не из функций отрисовки.
 */

#include <optional>
#include <span>
#include <string>
#include <vector>

#include "harmony/core/keyVocabulary.h"
#include "harmony/core/model/remoteConfig.h"
#include "harmony/core/modelInfo.h"

namespace harmony {

/**
 * @brief Откуда имя взято в списке клавиш конкретной модели.
 *
 * Это не источник имени словаря (`NameSource`, K1): словарь знает, откуда имя вообще,
 * а здесь важно, какой источник ответил о клавишах этой модели.
 */
enum class KeySource {
    Profile,        ///< зона вида `Key` на фото профиля
    ProfileScreen,  ///< поле `key` ячейки экрана профиля: транспорт и цифры 1000/1100,
                    ///< Menu/Guide/Info/Exit на боковых панелях — назначаемая клавиша модели
    ScanTable,      ///< скан-таблица семейства или модели (K2)
    Config,         ///< имя уже есть в фактической конфигурации
    Printed,        ///< надпись на корпусе: Touch и другие модели без измеренного кода
};

/// Одна клавиша списка модели.
struct ModelKey {
    std::string name;                    ///< имя; для ProfileScreen может быть вне словаря
    std::optional<KeyCategory> category; ///< нет — имя вне словаря
    KeySource source;
};

/// Список назначаемых клавиш модели и решение о его полноте.
struct ModelKeys {
    std::vector<ModelKey> keys;
    /// Список исчерпывающий: клавиши вне него у модели точно нет. true — есть профиль
    /// (его зоны или ячейки экранов) или полная скан-таблица. Нужно C1 и A1, чтобы проверка
    /// не давала ложных запретов для неполного списка.
    bool complete = false;
    /// Нет ни профиля, ни таблицы, ни надписей по модели: UI предлагает весь словарь вида Key.
    bool vocabularyFallback = false;
};

/**
 * @brief Назначаемые клавиши модели.
 *
 * Порядок — как у нынешнего `RemoteView::hardKeyIds()`, чтобы сортировка списков программы не
 * менялась: 1) зоны вида `Key` профиля в порядке файла; 2) `key` ячеек экранов профиля
 * (экраны по алфавиту id, ячейки в порядке файла); 3) без профиля — скан-таблица семейства или
 * модели в порядке словаря, а если таблицы нет, но есть таблица надписей по модели, то она;
 * 4) имена физических кнопок конфигурации, которых нет выше, — в конец.
 *
 * Ключи ячеек экрана — назначаемые клавиши модели: они не физические зоны, и правила словаря
 * для `hardware.zones` на них не распространяются.
 *
 * @param model Сводка модели: id и архитектура из каталога.
 * @param profileKeys Зоны вида `Key` профиля в порядке файла; пусто — профиля нет.
 * @param profileScreenKeys Поле `key` ячеек экранов профиля в том порядке, в каком их читает
 *        приложение (экраны по алфавиту id, ячейки по файлу).
 * @param config Фактическая конфигурация; nullptr — без конфигурации.
 * @return Список без повторов: имя встречается один раз, у него один источник.
 */
[[nodiscard]] ModelKeys modelKeys(const ModelInfo& model,
                                  std::span<const std::string> profileKeys,
                                  std::span<const std::string> profileScreenKeys,
                                  const model::RemoteConfig* config);

} // namespace harmony
