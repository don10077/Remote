#pragma once

/**
 * @file deviceReplacement.h
 * @brief Замена устройства в активностях: новый телевизор встаёт на место старого.
 *
 * В выбранных активностях всё, что относилось к старому устройству, переходит
 * к новому: включение и выключение, роли, переключение входа, шаги запуска,
 * аппаратные и экранные кнопки. Команды сопоставляются по имени (с учётом
 * написания и привычных синонимов) или по таблице, которую задал пользователь.
 * Кнопки и шаги с командами, которых у нового устройства нет, убираются —
 * на пульте они бы не сработали. «Кнопка Off» не меняется: в ней у каждого
 * устройства своя строка.
 */

#include <map>
#include <string>
#include <vector>

namespace harmony {

/// Что заменить.
struct DeviceReplacement {
    std::string oldId;                  ///< Прежнее устройство
    std::string newId;                  ///< Новое устройство
    std::vector<std::string> activities; ///< Активности (id); пусто — все, где есть прежнее
    /// Команда прежнего → команда нового; нет в таблице — подбирается само; пустая — убрать.
    std::map<std::string, std::string> commands;
    bool removeOld = false; ///< Удалить прежнее устройство, если оно больше нигде не нужно
};

/// Что получилось.
struct DeviceReplacementReport {
    int activities = 0; ///< Активностей изменено
    int buttons = 0;    ///< Кнопок перешло к новому устройству
    int steps = 0;      ///< Шагов запуска перешло
    int macroSteps = 0; ///< Шагов макросов перешло (кнопки-макросы активностей)
    int removed = 0;    ///< Кнопок и шагов убрано (команды нет у нового)
    int inputsLost = 0; ///< Переключений входа убрано (такого входа нет у нового)
    bool oldRemoved = false; ///< Прежнее устройство удалено
};

} // namespace harmony
