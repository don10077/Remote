#pragma once

/**
 * @file theme.h
 * @brief Оформление приложения: палитра, таблица стилей, шрифт.
 *
 * Основная тема — resources/theme/modern.qss. Новые элементы (шапка, стартовый
 * экран) — в harmony.qss: там цвета задаются токенами вида @accent, а
 * theme::apply() подставляет значения из палитры (theme.cpp).
 * Виджеты, которые рисуют себя сами (значки, списки), берут цвета через theme::color().
 */

#include <QColor>

namespace harmony::app::theme {

/**
 * @brief Именованные цвета палитры.
 */
enum class Color {
    Window,       ///< Фон окна и боковой панели
    Surface,      ///< Рабочая область (белая)
    SurfaceAlt,   ///< Чередование строк, подложки
    Border,       ///< Рамки и разделители
    Text,         ///< Основной текст
    TextMuted,    ///< Второстепенный текст (контрастный, не «серый на сером»)
    Accent,       ///< Акцент: главная кнопка, выделение
    AccentHover,  ///< Акцент при наведении
    AccentSoft,   ///< Мягкий фон выделения
    Success,      ///< «Подключено», «всё в порядке»
    Warning,      ///< Предупреждения
    Danger,       ///< Ошибки
    // Легенда картинки пульта (правая панель): образцы подсветки кнопок.
    RemoteKey,         ///< Кнопка пульта
    RemoteKeyFree,     ///< Свободная кнопка: заливка
    RemoteKeyFreeLine, ///< Свободная кнопка: пунктир
    RemoteBroken,      ///< Кнопка без команды (как BROKEN_LINE в remoteView)
    RemoteSelected,    ///< Выбранная кнопка (как SELECT_LINE в remoteView)
};

/**
 * @brief Цвет палитры.
 * @param role Имя цвета.
 * @return Цвет из палитры приложения.
 */
QColor color(Color role);

/**
 * @brief Применяет оформление ко всему приложению.
 *
 * Ставит шрифт и таблицу стилей: modern.qss (основная тема) и harmony.qss
 * (новые элементы, цвета из палитры). Тёмная тема (настройка или система):
 * цвета modern.qss перекрашиваются, палитра Qt — тёмная. Вызывать после
 * создания QApplication; можно и позже — при смене темы.
 * @return false, если таблицу стилей не удалось загрузить из ресурсов
 *         (приложение продолжит работу со стилем Qt по умолчанию).
 */
bool apply();

/// @return Применена тёмная тема (по настройке или по системе).
[[nodiscard]] bool isDark();

} // namespace harmony::app::theme
