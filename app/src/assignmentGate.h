#pragma once

/**
 * @file assignmentGate.h
 * @brief Единственное место, где решается, можно ли менять кнопки документа.
 *
 * Правило блока A (шаг A1): гейт назначения — «есть документ», а не «есть фото». Список
 * клавиш модели больше ничего не запрещает: он нужен, чтобы решить, на какую клавишу можно
 * назначить. Два решения разделены:
 *
 * 1. `gateOpen(hasDocument)` — открыты ли действия с кнопками.
 * 2. `buttonAllowed(button, keys, action, emptyNameAllowed)` — разрешено действие с конкретной
 *    кнопкой, где `keys` — ответ `harmony::modelKeys()` (K4).
 *
 * Назначить команду на клавишу, которой у модели нет, нельзя (Q5), но только когда список
 * исчерпывающий (`complete`): у неполного списка (880, 525) клавиша вне него может
 * существовать. Если такое назначение уже есть в конфигурации, оно не удаляется, а
 * подсвечивается в предупреждениях (C1), поэтому снять или перенести назначение с такой
 * клавиши разрешено — иначе предупреждение нельзя исправить.
 *
 * Когда по модели ответить нечем (`vocabularyFallback`), допустим весь словарь вида `Key`:
 * такой список не исчерпывающий, поэтому он не запрещает назначений.
 */

#include "harmony/core/modelKeys.h"

#include "widgets/buttonRef.h"

namespace harmony::app {

/// Какое действие решается — от этого зависит, нужна ли клавиша в списке модели.
enum class ButtonAction {
    AssignTo,  ///< назначить или перенести на кнопку: клавиша должна быть в списке модели
    TakeFrom,  ///< снять или переносить назначение с кнопки: клавиша вне списка разрешена
};

/// @param hasDocument Открыт документ (Q3: документ без модели — как модель без профиля).
/// @return true — действия с кнопками открыты.
[[nodiscard]] bool gateOpen(bool hasDocument);

/**
 * @brief Разрешает действие с конкретной кнопкой по правилу блока A.
 *
 * Место экранной кнопки здесь не проверяется: проверка `position < 0` остаётся на месте вызова
 * (`assignCommand`), как в T4 — она нужна, чтобы отличить новую кнопку от существующей.
 *
 * @param button Аппаратная клавиша (имя) или экранная кнопка (место).
 * @param keys Ответ `harmony::modelKeys()` для модели документа.
 * @param action Что решается: назначить на кнопку или работать с уже существующим назначением.
 * @param emptyNameAllowed Пустое имя можно: клавишу ещё выбирается в окне (`editButton`).
 * @return true — действие разрешено.
 */
[[nodiscard]] bool buttonAllowed(const ButtonRef& button, const harmony::ModelKeys& keys,
                                 ButtonAction action, bool emptyNameAllowed);

} // namespace harmony::app
